function normalize(value) {
  return String(value || '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase();
}

function isLedAdvertisingRequest(message) {
  const text = normalize(message);
  const ledContext = /(ecran\s+(?:geant|led)|affichage\s+(?:sur\s+)?ecran\s+led|panneau\s+led|led\s+exterieur|espace\s+c\b|4\s*[x×]\s*2\s*(?:m|metres?)|signage)/.test(text);
  const creativeContext = /(video|publicit|promo|campagne|storyboard|scenario|visuel|automobil|creation|creer|generer|produire)/.test(text);
  return ledContext && creativeContext;
}

function hasLedCreativeApproval(value) {
  const text = normalize(value);
  if (/\[led_creative_approved\]/.test(text)) return true;
  if (/validation\s+creative\s+led\s*:\s*(?:validee|approuvee|confirmee)/.test(text)) return true;
  const copyApproved = /(?:textes?|copy|message).{0,80}(?:valid|approuv|confirm)/.test(text);
  const contactApproved = /(?:coordonnees|telephone|contact|site\s+internet).{0,80}(?:valid|approuv|confirm)/.test(text);
  const storyboardApproved = /(?:decoupage|storyboard|scenario).{0,80}(?:valid|approuv|confirm)/.test(text);
  return copyApproved && contactApproved && storyboardApproved;
}

